"""Multi-Agent Swarm Orchestrator for EDITH.

Implements Sections 84, 103, and Appendix B of the Master Engineering Constitution.
Orchestrates parallel subagents (Architect, Coder, Researcher, and Security Auditor)
collaborating through a shared blackboard memory architecture.
"""

from __future__ import annotations

import asyncio
import json
import logging
import time
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Callable, Dict, List, Optional

from edith.core.event_bus import BUS
from edith.core.security import SECURITY
from edith.core.state_machine import STATE, SystemState
from edith.providers.base import ModelResponse
from edith.providers.router import ROUTER, TaskCategory

logger = logging.getLogger("edith.tasks.agent_swarm")


class SwarmRole(str, Enum):
    """Specialized subagent personas in the EDITH swarm."""
    ARCHITECT = "EDITH-ARCHITECT"
    CODER = "EDITH-CODING-AGENT"
    RESEARCHER = "EDITH-RESEARCHER"
    AUDITOR = "EDITH-SECURITY-AUDITOR"


@dataclass
class SubagentReport:
    """Report generated by an individual subagent."""
    role: SwarmRole
    perspective: str
    content: str
    duration_ms: float
    success: bool = True
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class SwarmResult:
    """Consolidated consensus result from all participating swarm agents."""
    goal: str
    consensus: str
    reports: List[SubagentReport] = field(default_factory=list)
    total_duration_ms: float = 0.0
    success: bool = True


class AgentSwarm:
    """Orchestrates multi-agent parallel reasoning, coding, and security audits."""

    def __init__(self, router=None):
        self.router = router or ROUTER

    async def execute_swarm(
        self,
        goal: str,
        roles: Optional[List[SwarmRole]] = None,
        context: str = "",
    ) -> SwarmResult:
        """Run concurrent subagent evaluations and synthesize consensus."""
        t_start = time.perf_counter()
        clean_goal = (goal or "").strip()
        active_roles = roles or [
            SwarmRole.ARCHITECT,
            SwarmRole.CODER,
            SwarmRole.RESEARCHER,
            SwarmRole.AUDITOR,
        ]

        STATE.set_state_sync(SystemState.EXECUTING, reason=f"Swarm active with {len(active_roles)} agents")
        BUS.publish_sync("swarm:started", {"goal": clean_goal, "roles": [r.value for r in active_roles]})

        # Run all subagents concurrently
        tasks = [
            self._invoke_subagent(role=role, goal=clean_goal, context=context)
            for role in active_roles
        ]
        reports: List[SubagentReport] = await asyncio.gather(*tasks, return_exceptions=False)

        # Synthesize consensus from reports
        consensus = await self._synthesize_consensus(goal=clean_goal, reports=reports)
        total_dt = (time.perf_counter() - t_start) * 1000.0

        BUS.publish_sync(
            "swarm:completed",
            {
                "goal": clean_goal,
                "reports_count": len(reports),
                "duration_ms": total_dt,
            },
        )
        STATE.set_state_sync(SystemState.READY, reason="Swarm execution complete")

        return SwarmResult(
            goal=clean_goal,
            consensus=consensus,
            reports=reports,
            total_duration_ms=total_dt,
            success=True,
        )

    async def _invoke_subagent(self, role: SwarmRole, goal: str, context: str) -> SubagentReport:
        """Execute a single specialized subagent persona."""
        t0 = time.perf_counter()
        system_prompts = {
            SwarmRole.ARCHITECT: (
                "You are EDITH-ARCHITECT. Analyze system boundaries, module decoupling, "
                "state invariants, and architectural elegance. Be concise and rigorous."
            ),
            SwarmRole.CODER: (
                "You are EDITH-CODING-AGENT. Provide implementation details, algorithms, "
                "edge-case protections, and zero-defect code patterns. Be precise."
            ),
            SwarmRole.RESEARCHER: (
                "You are EDITH-RESEARCHER. Investigate documentation, best practices, "
                "industry benchmarks, and upstream standard specifications."
            ),
            SwarmRole.AUDITOR: (
                "You are EDITH-SECURITY-AUDITOR. Audit threat vectors, prompt injection risks, "
                "permission scopes, and fail-safe recovery invariants."
            ),
        }

        sys_prompt = system_prompts.get(role, "You are an EDITH specialist subagent.")
        user_prompt = f"Goal: {goal}\n"
        if context:
            user_prompt += f"Context: {context}\n"
        user_prompt += "Deliver your specialized analysis and recommendations."

        try:
            resp: ModelResponse = await self.router.execute(
                prompt=user_prompt,
                category=TaskCategory.CODING if role == SwarmRole.CODER else TaskCategory.GENERAL,
                system_prompt=sys_prompt,
            )
            content = resp.content.strip() if resp and resp.content else "No output provided."
            dt = (time.perf_counter() - t0) * 1000.0
            return SubagentReport(
                role=role,
                perspective=role.value,
                content=content,
                duration_ms=dt,
                success=True,
            )
        except Exception as ex:
            dt = (time.perf_counter() - t0) * 1000.0
            logger.error("Subagent %s failed: %s", role.value, ex)
            return SubagentReport(
                role=role,
                perspective=role.value,
                content=f"Error during analysis: {ex}",
                duration_ms=dt,
                success=False,
            )

    async def _synthesize_consensus(self, goal: str, reports: List[SubagentReport]) -> str:
        """Synthesize subagent perspectives into a unified consensus action plan."""
        synthesis_input = f"User Goal: {goal}\n\nSubagent Perspectives:\n"
        for rep in reports:
            synthesis_input += f"### {rep.perspective}\n{rep.content}\n\n"

        synthesis_prompt = (
            "You are EDITH Master Intelligence. Synthesize the subagent findings above into "
            "a unified, actionable consensus plan. Prioritize architectural safety, efficiency, and clarity."
        )

        try:
            resp: ModelResponse = await self.router.execute(
                prompt=synthesis_input,
                category=TaskCategory.REASONING,
                system_prompt=synthesis_prompt,
            )
            return resp.content.strip() if resp and resp.content else "Consensus synthesized."
        except Exception as ex:
            logger.error("Consensus synthesis failed: %s", ex)
            return f"Consensus synthesis error: {ex}"


# Global Singleton Instance
AGENT_SWARM = AgentSwarm()
